BEGIN;
CREATE TABLE IF NOT EXISTS public.hospitales_reportantes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL UNIQUE,
    nombre VARCHAR(160) NOT NULL,
    token_sha256 CHAR(64) NOT NULL UNIQUE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.reportes_hospitalarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio VARCHAR(36) UNIQUE,
    hospital_id BIGINT NOT NULL REFERENCES public.hospitales_reportantes(id),
    area VARCHAR(120) NOT NULL,
    equipo VARCHAR(160) NOT NULL,
    marca VARCHAR(80),
    modelo VARCHAR(80),
    numero_serie VARCHAR(100),
    inventario VARCHAR(100),
    tipo VARCHAR(24) NOT NULL CHECK (tipo IN ('fuera_servicio','correctivo','preventivo','instalacion','apertura')),
    prioridad VARCHAR(10) NOT NULL CHECK (prioridad IN ('baja','media','alta','critica')),
    descripcion TEXT NOT NULL,
    reportante VARCHAR(120) NOT NULL,
    contacto VARCHAR(150) NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'recibido'
      CHECK (estado IN ('recibido','en_revision','asignado','programado','en_proceso','pendiente_refacciones','finalizado','cancelado')),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_reportes_hospitalarios_estado_fecha
  ON public.reportes_hospitalarios (estado, creado_en DESC);
CREATE INDEX IF NOT EXISTS idx_reportes_hospitalarios_hospital_fecha
  ON public.reportes_hospitalarios (hospital_id, creado_en DESC);

CREATE TABLE IF NOT EXISTS public.reportes_hospitalarios_historial (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporte_id BIGINT NOT NULL REFERENCES public.reportes_hospitalarios(id),
    estado_anterior VARCHAR(30),
    estado_nuevo VARCHAR(30) NOT NULL,
    nota TEXT,
    actor VARCHAR(120) NOT NULL,
    fecha TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_reportes_hospitalarios_historial_reporte
  ON public.reportes_hospitalarios_historial (reporte_id, fecha DESC);
COMMIT;
